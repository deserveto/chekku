#!/usr/bin/env node
/**
 * One-off seed script: creates one APPROVED social post in Garage so the
 * Visual Content Agent flow can be tested end-to-end without waiting for the
 * weekly workflow (which creates DRAFT posts) or building an approval UI.
 *
 * Usage (from repo root, after `npm run dev:sh` has started Garage):
 *
 *   node scripts/seed-approved-post.mjs
 *
 * Prints the postId and the studio URL. Safe to run repeatedly — each run
 * creates a new post with a fresh id.
 */
import { readFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..');

// --- Load Garage config from storage/.env.local (generated by setup-env.sh) ---
function loadEnvFile(filePath) {
  const text = readFileSync(filePath, 'utf8');
  const env = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith("'") && value.endsWith("'")) || (value.startsWith('"') && value.endsWith('"'))) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

const garageEnv = loadEnvFile(resolve(repoRoot, 'storage/.env.local'));
const ENDPOINT = garageEnv.GARAGE_ENDPOINT;
const REGION = garageEnv.GARAGE_REGION || 'garage';
const BUCKET = garageEnv.GARAGE_BUCKET;
const ACCESS_KEY = garageEnv.GARAGE_ACCESS_KEY_ID;
const SECRET_KEY = garageEnv.GARAGE_SECRET_ACCESS_KEY;

if (!ENDPOINT || !BUCKET || !ACCESS_KEY || !SECRET_KEY) {
  console.error('Missing Garage config in storage/.env.local. Run "npm run setup" first.');
  process.exit(1);
}

// --- S3 client ---
const s3 = new S3Client({
  endpoint: ENDPOINT,
  region: REGION,
  forcePathStyle: true,
  credentials: { accessKeyId: ACCESS_KEY, secretAccessKey: SECRET_KEY },
});

// --- Namespace prefix (matches createNamespacedObjectStorage) ---
const AGENT_ID = 'social-media-agent';
const NAMESPACE = `agents/${Buffer.from(AGENT_ID).toString('base64url')}/`;

// --- Canonical post id ---
const now = new Date();
const stamp = now.toISOString().replace(/[-:.TZ]/g, '').slice(0, 14);
const hex = randomBytes(4).toString('hex');
const postId = `smp_${stamp}_${hex}`;

const postMarkdown = `**Hook:** Hari Guru Nasional — mereka yang membentuk masa depan.

Hari ini kita merayakan dedikasi, kesabaran, dan cinta para guru. Setiap pelajaran yang mereka berikan adalah benih yang tumbuh untuk masa depan yang lebih baik. Terima kasih, Guru — jasa kalian tak akan terlupakan.

#HariGuruNasional #PahlawanTanpaTandaJasa`;

const briefMarkdown = `Topic: Hari Guru Nasional
Platform: Instagram
Tone: Warm, appreciative, reflective
Objective: Honour teachers and their dedication`;

const metadata = {
  postId,
  createdAt: now.toISOString(),
  platform: 'instagram',
  topic: 'Hari Guru Nasional',
  specialDay: 'Hari Guru Nasional',
  status: 'APPROVED',
  postObjectKey: `social-posts/${postId}/post.md`,
  briefObjectKey: `social-posts/${postId}/brief.md`,
  metadataObjectKey: `social-posts/${postId}/metadata.json`,
};

async function putObject(key, body, contentType) {
  await s3.send(new PutObjectCommand({
    Bucket: BUCKET,
    Key: `${NAMESPACE}${key}`,
    Body: body,
    ContentType: contentType,
  }));
}

// Write brief → post → metadata (metadata last, matching the workflow order)
await putObject(`social-posts/${postId}/brief.md`, briefMarkdown, 'text/markdown');
await putObject(`social-posts/${postId}/post.md`, postMarkdown, 'text/markdown');
await putObject(`social-posts/${postId}/metadata.json`, JSON.stringify(metadata, null, 2), 'application/json');

console.log('');
console.log('Seeded APPROVED social post:');
console.log('  postId:        ', postId);
console.log('  status:        APPROVED');
console.log('');
console.log('Studio URLs:');
console.log(`  post detail:   http://localhost:3000/social-posts/${postId}`);
console.log(`  post list:     http://localhost:3000/social-posts`);
console.log('');
console.log('Next: open the Social Media Supervisor in the studio and ask:');
console.log(`  "Generate an image for post ${postId}"`);
console.log('');
